#!/usr/bin/env python3
"""
Weather badge icons (IDEA-20) -> mods/rapx/uibits/px-weather.png and px-weather-2x.png.

White glyphs, tinted per weather by PxWeatherBadgeWidget at draw time:
  row y=0   32x32 cells: large icon (28 px glyph)
  row y=32  32x32 cells: soft glow of the large icon (blurred, for the halo behind it)
  row y=64  20x20 cells: small forecast icon (16 px glyph)
Regions are written to mods/rapx/px-weather.yaml (collection px-weather-icons).
Icons are game-icons.net SVGs (CC BY 3.0, see ../px-sidebar/icons/LICENSE.md), rasterised with rsvg-convert.

Run: python3 artsrc/px-weather/generate.py
"""

import io
import os
import subprocess
from PIL import Image, ImageFilter

SS = 4
HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = os.path.join(HERE, "..", "px-sidebar", "icons")
MOD = os.path.join(HERE, "..", "..", "mods", "rapx")

# weather id (PxWeatherType lower-case) -> svg
WEATHER = [
    ("clear", "sun"), ("rain", "raining"), ("thunderstorm", "lightning-storm"), ("snow", "snowing"),
    ("blizzard", "snowflake-2"), ("fog", "fog"), ("sandstorm", "sandstorm"), ("strongwind", "windy-stripes"),
    ("heathaze", "heat-haze"),
]

W, H = 512, 128  # OpenRA textures must be power-of-two sized
sheet = Image.new("RGBA", (W * SS, H * SS), (0, 0, 0, 0))


def raster(name, size):
    png = subprocess.run(["rsvg-convert", "-w", str(size * SS), "-h", str(size * SS), os.path.join(ICONS, name + ".svg")],
                         check=True, capture_output=True).stdout
    # game-icons SVGs draw a black square behind a white glyph: keep only the glyph
    return Image.open(io.BytesIO(png)).convert("L")


def place(mask, x, y):
    glyph = Image.new("RGBA", mask.size, (255, 255, 255, 255))
    glyph.putalpha(mask)
    sheet.alpha_composite(glyph, (x * SS, y * SS))


regions = []
for i, (wid, svg) in enumerate(WEATHER):
    big = raster(svg, 28)
    place(big, i * 32 + 2, 2)
    regions.append(f"\t\t{wid}: {i * 32}, 0, 32, 32")

    # Glow: the glyph grown and blurred, kept inside its 32px cell
    glow = Image.new("L", (32 * SS, 32 * SS), 0)
    glow.paste(big, (2 * SS, 2 * SS))
    glow = glow.filter(ImageFilter.MaxFilter(9)).filter(ImageFilter.GaussianBlur(3.2 * SS))
    glow = glow.point(lambda a: int(a * 0.85))
    place(glow, i * 32, 32)
    regions.append(f"\t\t{wid}-glow: {i * 32}, 32, 32, 32")

    small = raster(svg, 16)
    place(small, i * 32 + 2, 66)
    regions.append(f"\t\t{wid}-small: {i * 32}, 64, 20, 20")

for scale, name in ((1, "px-weather.png"), (2, "px-weather-2x.png")):
    out = sheet.resize((W * scale, H * scale), Image.LANCZOS)
    out.save(os.path.join(MOD, "uibits", name))
    print("wrote", name, out.size)

with open(os.path.join(MOD, "px-weather.yaml"), "w") as f:
    f.write("# Weather badge icons (IDEA-20). Generated by artsrc/px-weather/generate.py - do not edit by hand.\n\n")
    f.write("px-weather-icons:\n\tImage: px-weather.png\n\tImage2x: px-weather-2x.png\n\tRegions:\n")
    f.write("\n".join(regions) + "\n")
print("wrote px-weather.yaml")
