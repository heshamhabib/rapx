#!/usr/bin/env python3
"""Draws the Language page flags: mods/rapx/uibits/px-lang-flags{,-2x,-3x}.png + mods/rapx/px-lang-flags.yaml.

One 180x120 flag per language (2 columns x 3 rows), rendered from the public domain SVGs in
artsrc/px-flags/svg. The Language page waves them with PxFlagDraw, so they are drawn flat here.
"""
import io
import os
import subprocess

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SVG_DIR = os.path.join(ROOT, "artsrc/px-flags/svg")
UIBITS = os.path.join(ROOT, "mods/rapx/uibits")
MOD = os.path.join(ROOT, "mods/rapx")

# Language id -> flag SVG. Keep in step with FluentLanguages in mods/rapx/mod.yaml.
FLAGS = [("en", "gb"), ("ar", "eg"), ("de", "de"), ("fr", "fr"), ("zh", "cn"), ("vi", "vn")]
W, H = 180, 120


def flag(code, w, h):
    png = subprocess.run(["rsvg-convert", "-h", str(h * 2), os.path.join(SVG_DIR, code + ".svg")],
                         check=True, capture_output=True).stdout
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    scale = max(w / img.width, h / img.height)
    img = img.resize((max(w, round(img.width * scale)), max(h, round(img.height * scale))), Image.LANCZOS)
    x, y = (img.width - w) // 2, (img.height - h) // 2
    return img.crop((x, y, x + w, y + h))


def pos(i):
    return (i % 2) * (W + 2), (i // 2) * (H + 2)


def main():
    for scale, suffix, size in [(1, "", 512), (2, "-2x", 1024), (3, "-3x", 2048)]:
        sheet = Image.new("RGBA", (size, size))
        for i, (_, code) in enumerate(FLAGS):
            x, y = pos(i)
            sheet.paste(flag(code, W * scale, H * scale), (x * scale, y * scale))
        sheet.save(os.path.join(UIBITS, f"px-lang-flags{suffix}.png"))

    with open(os.path.join(MOD, "px-lang-flags.yaml"), "w") as f:
        f.write("# GENERATED by artsrc/px-langs/generate.py - edit that script, not this file.\n")
        f.write("lang-flags:\n\tImage: px-lang-flags.png\n\tImage2x: px-lang-flags-2x.png\n\tImage3x: px-lang-flags-3x.png\n\tRegions:\n")
        for i, (lang, _) in enumerate(FLAGS):
            x, y = pos(i)
            f.write(f"\t\t{lang}: {x}, {y}, {W}, {H}\n")


if __name__ == "__main__":
    main()
