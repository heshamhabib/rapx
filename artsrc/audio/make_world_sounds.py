#!/usr/bin/env python3
"""
Turns the CC0 Freesound downloads (artsrc/audio/sfx/source/, fetched by fetch_freesound.py, sources listed in
artsrc/audio/sfx/SOURCE.md) into the weapon and world sounds (IDEA-31): mods/rapx/audio/sfx/<name>.ogg.

Each sound takes its loudest event from the chosen file: from just before the attack until it decays below -40 dB
(or MAX_LEN), with a short fade, levelled to the same loudness. CHOICE picks the file and, when the automatic cut
is wrong, a fixed start/length. To swap a sound, change its id here and re-run.

  python3 artsrc/audio/make_world_sounds.py
  python3 artsrc/audio/make_world_sounds.py cannon1 kaboom22
"""
import json
import os
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ogg  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "sfx", "source")
OUT = os.path.join(HERE, "..", "..", "mods", "rapx", "audio", "sfx")
SR = 44100

# name -> (freesound id, start or None for automatic, length or None)
CHOICE = json.load(open(os.path.join(HERE, "sfx", "choice.json")))

# longest a sound may run (seconds); big explosions ring out, UI-like clicks stay short
MAX_LEN = {"kaboom1": 6, "kaboom22": 3.5, "subshow1": 3.5, "build5": 3, "h2obomb2": 3, "tslachg2": 2.5,
           "kaboom30": 3, "missile1": 2.5, "torpedo1": 2.5, "turret1": 2.5, "tank5": 2.5}
DEFAULT_MAX = 2.0
# per-sound loudness (LUFS); explosions loud, small utility sounds quieter
LOUD = {"kaboom1": -10, "kaboom22": -11, "mineblo1": -11, "placbldg": -16, "cashturn": -16, "build5": -18,
        "fixit1": -17, "squishy2": -15, "minelay1": -16, "chute1": -17, "splash9": -16}
DEFAULT_LOUD = -13


def load(path):
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", path, "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32)


def auto_cut(x, max_len):
    hop = int(SR * 0.005)
    e = np.array([np.sqrt(np.mean(x[i:i + hop] ** 2)) + 1e-9 for i in range(0, len(x) - hop, hop)])
    db = 20 * np.log10(e / e.max())
    peak = int(np.argmax(db))
    start = peak
    while start > 0 and db[start - 1] > -30 and peak - start < 40:  # back up to the attack (max 200 ms)
        start -= 1
    end, quiet = peak, 0
    limit = start + int(max_len / 0.005)
    while end < min(len(db), limit):
        quiet = quiet + 1 if db[end] < -40 else 0
        if quiet > 20:
            break
        end += 1
    start = max(0, start - 2)
    return start * hop / SR, (end - start) * hop / SR


def build(name):
    sid, start, length = CHOICE[name]
    src = os.path.join(SRC, f"fs{sid}.mp3")
    max_len = MAX_LEN.get(name, DEFAULT_MAX)
    if start is None:
        start, length = auto_cut(load(src), max_len)
    length = min(length, max_len)
    fade = min(0.25, length * 0.3)
    os.makedirs(OUT, exist_ok=True)
    af = (f"atrim=start={start:.3f}:duration={length:.3f},asetpts=PTS-STARTPTS,highpass=f=30,"
          f"afade=t=in:d=0.004,afade=t=out:st={length - fade:.3f}:d={fade:.3f},"
          f"loudnorm=I={LOUD.get(name, DEFAULT_LOUD)}:TP=-1:LRA=20")
    ogg.encode(src, os.path.join(OUT, name + ".ogg"), ["-ac", "1", "-af", af, "-ar", str(SR)])
    return start, length


def silenced_shots():
    """Spy's silenced pistol: our own pistol shots (make_rifle_sounds.py), muffled and shortened."""
    weapons = os.path.join(HERE, "..", "..", "mods", "rapx", "audio", "weapons")
    for i in (1, 2, 3):
        ogg.encode(os.path.join(weapons, f"pistol-shot{i}.wav"), os.path.join(weapons, f"silenced-shot{i}.ogg"),
                   ["-ac", "1", "-af", "lowpass=f=1100,highpass=f=180,atrim=duration=0.25,"
                    "afade=t=out:st=0.12:d=0.13,volume=0.45", "-ar", str(SR)])


def write_sources():
    """artsrc/audio/sfx/SOURCE.md: the licence record for every file in use."""
    cand = json.load(open(os.path.join(HERE, "sfx", "candidates.json")))
    info = {c["id"]: c for v in cand.values() for c in v["candidates"]}
    rows = [f"| {name} | https://freesound.org/s/{sid}/ \"{info[sid]['title']}\" | {info[sid]['user']} | CC0 |"
            for name, (sid, _s, _l) in sorted(CHOICE.items())]
    with open(os.path.join(HERE, "sfx", "SOURCE.md"), "w") as fh:
        fh.write("# Weapon and world sound sources\n\nGenerated by `artsrc/audio/make_world_sounds.py`. Freesound "
                 "high-quality MP3 previews of CC0 sounds, saved as `source/fs<id>.mp3` by `fetch_freesound.py`. "
                 "CC0 needs no credit; listed so the licence of every sound can be checked.\n\n"
                 "| Game sound | Original | Author | Licence |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")


def main():
    for name in sys.argv[1:] or CHOICE:
        start, length = build(name)
        print(f"{name:9} fs{CHOICE[name][0]}  {start:.2f}s +{length:.2f}s")
    if not sys.argv[1:]:
        silenced_shots()
    write_sources()


if __name__ == "__main__":
    main()
