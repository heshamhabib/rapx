#!/usr/bin/env python3
"""
HD parachutes (RedAlert Project X, IDEA-30 phase 2).

  python3 artsrc/units/parachute/make_parachute.py [--skip-render] [--samples N]

Renders render_parachute.py with Blender (the Sketchfab "Army Parachute" by amaraklov, CC-BY-4.0), then writes
mods/rapx/bits/hd/fx/parachute/{parach,parabomb,parach-shadow}.png and mods/rapx/sequences/hd-parachute.yaml,
which replaces the classic `parach` (paratroopers and paradropped vehicles), `parach-shadow` and `parabomb` images.
Frames are cropped symmetrically round their centre: the engine draws the frame centre at the load.
"""
import argparse
import os
import subprocess

import numpy as np
from PIL import Image, PngImagePlugin
from scipy.ndimage import gaussian_filter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
RENDER = os.path.join(HERE, "render")
OUT = os.path.join(ROOT, "mods", "rapx", "bits", "hd", "fx", "parachute")
SEQUENCES = os.path.join(ROOT, "mods", "rapx", "sequences", "hd-parachute.yaml")
DENSITY = 3.0


def load(name):
    im = np.asarray(Image.open(os.path.join(RENDER, name + ".png")).convert("RGBA"), dtype=np.float32) / 255
    im[..., 3] = np.where(im[..., 3] < 0.03, 0, im[..., 3])
    return im


def save(name, frames):
    a = np.zeros(frames[0].shape[:2], bool)
    for f in frames:
        a |= f[..., 3] > 0.02
    ys, xs = np.nonzero(a)
    h, w = a.shape
    hw = min(w // 2, int(max(w / 2 - xs.min(), xs.max() + 1 - w / 2)) + 2)
    hh = min(h // 2, int(max(h / 2 - ys.min(), ys.max() + 1 - h / 2)) + 2)
    crop = [f[h // 2 - hh:h // 2 + hh, w // 2 - hw:w // 2 + hw] for f in frames]
    fh, fw, _ = crop[0].shape
    sheet = np.concatenate(crop, axis=1)
    info = PngImagePlugin.PngInfo()
    info.add_text("FrameSize", f"{fw},{fh}")
    info.add_text("FrameAmount", str(len(crop)))
    Image.fromarray((np.clip(sheet, 0, 1) * 255).astype(np.uint8)).save(os.path.join(OUT, name + ".png"),
                                                                       pnginfo=info, optimize=True)
    print(f"  {name}: {len(crop)} frames {fw}x{fh}")


def shadow():
    """Soft oval: the engine fills it with its shadow colour, so only the alpha counts."""
    w, h = int(30 * DENSITY), int(30 * 0.77 * DENSITY)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    r = np.sqrt(((xx - w / 2) / (w / 2)) ** 2 + ((yy - h / 2) / (h / 2)) ** 2)
    a = gaussian_filter(np.clip((1 - r) * 3, 0, 1), 2) * 0.85
    return [np.dstack([np.zeros((h, w, 3)), a]).astype(np.float32)]


def seq(name, file, start, length, extra=()):
    path = f"ra|bits/hd/fx/parachute/{file}.png"
    lines = [f"\t{name}:", f"\t\tFilename: {path}", "\t\tTilesetFilenames:"]
    lines += [f"\t\t\t{t}: {path}" for t in ("TEMPERAT", "SNOW", "DESERT", "INTERIOR")]
    lines += [f"\t\tStart: {start}", f"\t\tLength: {length}", "\t\tOffset: 0,0", f"\t\tScale: {1 / DENSITY:.4f}"]
    return lines + [f"\t\t{e}" for e in extra]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-render", action="store_true")
    ap.add_argument("--samples", type=int, default=64)
    args = ap.parse_args()
    if not args.skip_render:
        subprocess.run(["nice", "-n", "10", "blender", "-b", "-P", os.path.join(HERE, "render_parachute.py"), "--",
                        RENDER, str(args.samples)], check=True, stdout=subprocess.DEVNULL)
    os.makedirs(OUT, exist_ok=True)
    save("parach", [load(f"parach-open-{i}") for i in range(5)] + [load(f"parach-idle-{i}") for i in range(11)])
    save("parabomb", [load(f"parabomb-open-{i}") for i in range(8)] + [load(f"parabomb-idle-{i}") for i in range(5)])
    save("parach-shadow", shadow())
    y = ["# HD parachutes from the Sketchfab model \"Army Parachute\" by amaraklov (CC-BY-4.0) (RedAlert Project X).",
         "# GENERATED by artsrc/units/parachute/make_parachute.py - edit that script, not this file.", "",
         "parach:"] + seq("open", "parach", 0, 5, ["Tick: 80"]) + seq("idle", "parach", 5, 11, ["Tick: 110"])
    y += ["", "parach-shadow:"] + seq("idle", "parach-shadow", 0, 1)
    y += ["", "parabomb:"] + seq("open", "parabomb", 0, 8, ["ZOffset: 1023", "Tick: 60"])
    y += seq("idle", "parabomb", 8, 5, ["ZOffset: 1023", "Tick: 110"])
    with open(SEQUENCES, "w") as f:
        f.write("\n".join(y) + "\n")
    print("wrote", os.path.relpath(SEQUENCES, ROOT))


if __name__ == "__main__":
    main()
