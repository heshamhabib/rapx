#!/usr/bin/env python3
"""
Writes mods/rapx/sequences/hd-soldiers3d.yaml from the packed 3D soldier sheets in mods/rapx/bits/hd/soldiers/<id>/
(build_soldier.sh). Only sequences whose sheet exists are written, so a soldier can switch over one animation at a
time; everything else keeps its AI-sheet sprite from hd-infantry.yaml.

  python3 artsrc/units/soldiers/write_sequences.py
"""
import os

from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
BITS = os.path.join(ROOT, "mods", "rapx", "bits", "hd", "soldiers")
OUT = os.path.join(ROOT, "mods", "rapx", "sequences", "hd-soldiers3d.yaml")

# game sequence -> (sheet, frames to use (None = all), tick ms)
SEQUENCES = {
    "stand": ("idle", 1, None),
    "stand2": ("aim", 1, None),
    "idle1": ("idle", None, 280),
    "idle2": ("look", None, 280),
    "run": ("run", None, 100),
    "shoot": ("shoot", None, 70),
    "liedown": ("liedown", None, 60),
    "standup": ("standup", None, 60),
    "prone-stand": ("crawl", 1, None),
    "prone-stand2": ("crawl", 1, None),
    "prone-run": ("crawl", None, 150),
    "prone-shoot": ("proneshoot", None, 70),
    "die1": ("die1", None, 80),
    "die2": ("die2", None, 80),
    "die3": ("die1", None, 80),
    "die4": ("die2", None, 80),
    "die5": ("die2", None, 80),
    # make_deaths.py: electrocuted (ElectricityDeath) and crushed, built from the soldier's own renders
    "die6": ("die6", None, 80),
    "die-crushed": ("crushed", None, 1600),
    # hanging under the HD parachute (artsrc/units/parachute)
    "parachute": ("idle", 1, None),
}
# Extra keys per game sequence
EXTRA = {"die-crushed": ["ZOffset: -511"]}
# Size in game: 3x-density renders shown at 0.6 of a third (Balanced RTS proportions, same as make_infantry.py)
GAME_SCALE = 0.6 / 3
# Per soldier: game sequence names that differ (e.g. the Grenadier throws)
RENAME = {"e2": {"shoot": "throw", "prone-shoot": "prone-throw"}}
# Per soldier: extra game sequences their rules use, played with one of the sequences above. Anything the rules
# use that is not covered here falls back to the old AI sheet in hd-infantry.yaml (a different-looking soldier).
ALIASES = {
    "medi": {"idle": "idle1", "heal": "idle2"},      # WithInfantryBody IdleSequences: idle, DefaultAttackSequence: heal
    "mech": {"idle": "idle1", "repair": "idle2"},    # IdleSequences: idle, DefaultAttackSequence: repair
    "e7": {"shoot-left": "shoot", "shoot-right": "shoot",  # Tanya's two pistols (AttackSequences)
           "prone-shoot-left": "prone-shoot", "prone-shoot-right": "prone-shoot"},
    "spy": {"shoot": "stand2", "prone-shoot": "prone-stand"},   # fires his silenced pistol from the aiming pose
}
# Humanoid robots (IDEA-29): burnt / crushed deaths play the normal fall
for _r in ("cybt", "bdrd", "rgun", "irgd", "taut"):
    ALIASES[_r] = {"die6": "die1", "die-crushed": "die1"}

lines = ["# 3D soldiers (Mixamo-animated, rendered in Blender; see artsrc/units/soldiers/).",
         "# GENERATED by artsrc/units/soldiers/write_sequences.py - edit that script, not this file.",
         "# Overrides the AI-sheet sequences in hd-infantry.yaml for every sheet that exists. Frames run",
         "# counter-clockwise from north (UseClassicFacings: False), 192 px at 3x density.", ""]
for uid in sorted(os.listdir(BITS)) if os.path.isdir(BITS) else []:
    sheets = {}
    for fn in os.listdir(os.path.join(BITS, uid)):
        if fn.endswith(".png"):
            info = Image.open(os.path.join(BITS, uid, fn)).info
            sheets[fn[:-4]] = (int(info["FrameAmount"]), int(info.get("Facings", 1 if fn.startswith("die") else 32)))
    if not sheets:
        continue
    lines.append(uid + ":")
    for seq, (sheet, use, tick) in SEQUENCES.items():
        if sheet not in sheets:
            continue
        frames, facings = sheets[sheet]
        per_facing = frames // facings
        length = use or per_facing
        names = [RENAME.get(uid, {}).get(seq, seq)] + [a for a, base in ALIASES.get(uid, {}).items() if base == seq]
        for name in names:
            lines += [f"\t{name}:", f"\t\tFilename: ra|bits/hd/soldiers/{uid}/{sheet}.png", "\t\tStart: 0",
                      f"\t\tLength: {length}", f"\t\tStride: {per_facing}", f"\t\tFacings: {facings}",
                      "\t\tUseClassicFacings: False", f"\t\tScale: {GAME_SCALE:.4f}"]
            if tick:
                lines.append(f"\t\tTick: {tick}")
            lines += [f"\t\t{e}" for e in EXTRA.get(seq, [])]
            if seq in ("die6", "die-crushed"):
                # the classic deaths have snow variants and a Frames list that would otherwise merge in
                path = f"ra|bits/hd/soldiers/{uid}/{sheet}.png"
                lines += ["\t\tTilesetFilenames:"] + [f"\t\t\t{t}: {path}" for t in ("TEMPERAT", "SNOW", "DESERT", "INTERIOR")]
                lines.append("\t\tFrames: " + ", ".join(str(i) for i in range(length)))
    lines.append("")
open(OUT, "w").write("\n".join(lines))
print("wrote", OUT)
