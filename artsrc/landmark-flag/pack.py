#!/usr/bin/env python3
"""Packs the rendered landmark-flag frames (render_flag.py) into game sprites.

Output: mods/rapx/bits/hd/landmark-flag/<faction>.png (the pole, plinth and national cloth: never recoloured) and
team.png (the pennant and the plinth band, pure green: PlayerColorShift paints them in the owner's colour), FRAMES
frames side by side; mods/rapx/sequences/hd-landmark-flag.yaml (image `pxlandmarkflag`)."""
import glob
import os

import numpy as np
from PIL import Image, PngImagePlugin

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
FR = os.path.join(HERE, "build", "frames")
OUT = os.path.join(ROOT, "mods", "rapx", "bits", "hd", "landmark-flag")
SEQ = os.path.join(ROOT, "mods", "rapx", "sequences", "hd-landmark-flag.yaml")


def load(path):
    return np.asarray(Image.open(path).convert("RGBA")).astype(np.float32) / 255


def save(name, frames):
    h, w, _ = frames[0].shape
    info = PngImagePlugin.PngInfo()
    info.add_text("FrameSize", f"{w},{h}")
    info.add_text("FrameAmount", str(len(frames)))
    Image.fromarray((np.clip(np.concatenate(frames, axis=1), 0, 1) * 255).astype(np.uint8)).save(
        os.path.join(OUT, name + ".png"), pnginfo=info, optimize=True)


os.makedirs(OUT, exist_ok=True)
masks = sorted(glob.glob(os.path.join(FR, "mask-*.png")))
nations = sorted({os.path.basename(p)[:-7] for p in glob.glob(os.path.join(FR, "*.png"))} - {"mask"})
team_frames = None
for n in nations:
    cloth, team = [], []
    for i, mp in enumerate(masks):
        m = load(mp)
        tm = (m[..., :3].mean(-1) * m[..., 3])[..., None]
        f = load(os.path.join(FR, f"{n}-{i:02d}.png"))
        c = f.copy()
        c[..., 3] = f[..., 3] * (1 - tm[..., 0])
        cloth.append(c)
        t = f.copy()
        t[..., 3] = f[..., 3] * tm[..., 0]
        team.append(t)
    save(n, cloth)
    if team_frames is None:
        team_frames = team
save("team", team_frames)
lines = ["# Landmark flag shown on captured landmarks (rules/civilian.yaml ^PxCashLandmark).",
         "# GENERATED by artsrc/landmark-flag/pack.py - edit that script, not this file.", "", "pxlandmarkflag:",
         "\tDefaults:", "\t\tScale: 0.25", f"\t\tLength: {len(masks)}", "\t\tTick: 90", "\tteam:",
         "\t\tFilename: ra|bits/hd/landmark-flag/team.png"]
for n in nations:
    lines += [f"\tcloth-{n}:", f"\t\tFilename: ra|bits/hd/landmark-flag/{n}.png"]
open(SEQ, "w").write("\n".join(lines) + "\n")
print(len(nations), "nations,", len(masks), "frames ->", OUT)
