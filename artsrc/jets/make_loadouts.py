#!/usr/bin/env python3
"""
IDEA-34: writes the jet loadout rules and overlay sequences from artsrc/jets/loadout_table.py and the weapon positions
recorded by the importer (artsrc/units/meshes/<sprite>.stores.json):

  mods/rapx/rules/jet-loadouts.yaml       per jet: ammo pools, armaments, weapon overlays, gun
  mods/rapx/sequences/jet-loadouts.yaml   per jet: one overlay sequence per weapon (trimmed <sprite>-stores.png)

  python3 artsrc/jets/make_loadouts.py

How a station works: a left/right pair is one AmmoPool (one ammo per missile, refilled only at the airfield) and one
Armament firing the family's .Pair weapon (Burst 2: the first listed pylon, then the second). Each missile's overlay
shows while the pool still holds its shot (first pylon: >= 2 x shots... see overlay_condition), so it vanishes when
fired. Inner stations of a family wait until the outer ones are empty. The gun has a small pool too, so a jet that has
fired everything flies home to rearm (FlyAttack returns when every armament that could hit the target is paused).
Jets with air-to-air missiles fly combat air patrol: they engage enemy aircraft on their own (jets fight jets).
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "artsrc", "units", "meshes"))
from loadout_table import LOADOUTS  # noqa: E402
from sketchfab_models import MODELS  # noqa: E402

RULES = os.path.join(ROOT, "mods", "rapx", "rules", "jet-loadouts.yaml")
SEQUENCES = os.path.join(ROOT, "mods", "rapx", "sequences", "jet-loadouts.yaml")
GUN_AMMO = 6  # gun bursts per sortie
MISSILE_WEAPONS = os.path.join(ROOT, "mods", "rapx", "weapons", "jet-missiles.yaml")

# Which missile each station fires (its pxmissile sprite, artsrc/jets/make_missiles.sh): the station's "missile", its
# "add" kind, else the family's missile for the jet's side. Families keep their own sprite (weapons/jet-ordnance.yaml)
# for the Western default; other kinds get a generated variant <family>.<kind> in weapons/jet-missiles.yaml.
EAST_JETS = {"mig", "jet.mig21", "jet.mig23", "jet.mig25", "jet.su25", "jet.su27", "jet.su35", "jet.su47", "jet.l39",
             "jet.j20", "jet.tu160", "hind", "mi35", "ka52"}
SIDE_MISSILES = {
    "west": {"JetAAM.Short": "aim9", "JetAAM.Medium": "aim120", "JetAAM.Long": "aim54", "JetAGM": "agm65",
             "JetGBU": "gbu", "JetBomb": "mk82", "JetCluster": "mk82", "JetWP": "mk82", "JetNapalm": "mk82", "JetRockets": "hydra"},
    "east": {"JetAAM.Short": "r73", "JetAAM.Medium": "r27t", "JetAAM.Long": "r77", "JetAGM": "kh29",
             "JetGBU": "gbu", "JetBomb": "mk82", "JetCluster": "mk82", "JetWP": "mk82", "JetNapalm": "mk82", "JetRockets": "s8"},
}


def station_missile(unit, family, table_station):
    side = "east" if unit in EAST_JETS else "west"
    kind = table_station.get("missile") or table_station.get("add")
    if kind in (None, "pod"):
        kind = SIDE_MISSILES[side][family]
    return kind


def weapon_for(family, kind, used):
    """The family's weapon, or its generated variant when the station fires another missile."""
    if kind == SIDE_MISSILES["west"][family]:
        return family
    used.add((family, kind))
    return f"{family}.{kind}"
HEADER = "# GENERATED by artsrc/jets/make_loadouts.py from artsrc/jets/loadout_table.py (IDEA-34) - edit those, not this.\n"


def offset(p, wdist, height):
    x, y, z = p
    return f"{round(y * wdist)},{round(x * wdist)},{round(z * wdist * height)}"


def parents():
    """actor -> the actor it inherits from (rules/aircraft.yaml + jets.yaml; first plain Inherits)."""
    import re
    out = {}
    for name in ("aircraft.yaml", "jets.yaml"):
        text = open(os.path.join(ROOT, "mods", "rapx", "rules", name)).read()
        for m in re.finditer(r"^([A-Z0-9.]+):\n\tInherits: ([A-Z0-9.]+)$", text, re.M):
            out[m.group(1)] = m.group(2)
    return out


# The targeting an aircraft has before IDEA-34 (^AutoTargetGroundAssaultMove + MIG's HoldFire), for jets whose
# parent became a fighter but which are not fighters themselves
GROUND_TARGETING = ["\tAutoTarget:", "\t\tInitialStance: HoldFire", "\t\tInitialStanceAI: HoldFire",
                    "\tAutoTargetPriority@DEFAULT:", "\t\tValidTargets: Infantry, Vehicle, Ship, Underwater, Defense, Mine",
                    "\tAutoTargetPriority@ATTACKANYTHING:",
                    "\t\tValidTargets: Infantry, Vehicle, Ship, Underwater, Structure, Defense, Mine"]
ORIGINAL_WEAPONS = ["\tArmament:", "\t\tWeapon: Maverick", "\t\tLocalOffset: 0,-640,0, 0,640,0", "\t\tLocalYaw: -40, 24",
                    "\t\tPauseOnCondition: !ammo", "\tAmmoPool:", "\t\tAmmo: 8", "\t\tAmmoCondition: ammo",
                    "\tAttackAircraft:", "\t\tArmaments: primary"]
AIR_TARGETING = ["\tAutoTarget:", "\t\tInitialStance: AttackAnything", "\t\tInitialStanceAI: AttackAnything",
                 "\tAutoTargetPriority@DEFAULT:", "\t\tValidTargets: AirborneActor",
                 "\tAutoTargetPriority@ATTACKANYTHING:", "\t\tValidTargets: AirborneActor"]


def main():
    rules, seqs = [HEADER], [HEADER]
    parent = parents()
    aircraft_rules = open(os.path.join(ROOT, "mods", "rapx", "rules", "aircraft.yaml")).read()
    built = {}  # actor -> (trait keys it adds, is fighter)
    blocks = {}
    used = set()
    for unit, table in LOADOUTS.items():
        cfg = MODELS[unit]
        sprite = cfg.get("out", unit)
        path = os.path.join(ROOT, "artsrc", "units", "meshes", f"{sprite}.stores.json")
        if not os.path.exists(path):
            print(f"{unit}: no {path} yet (render it with make_sketchfab.py) - skipped")
            continue
        data = json.load(open(path))
        wdist, height = data["wdist_per_unit"], data["height_factor"]
        actor, image = unit.upper(), unit
        tag = unit.replace("jet.", "").replace(".", "").upper()  # unique per jet: inherited ones can be removed
        lines, keys, names, frame = [], [], [], 0
        seq = [f"\n{image}:"]
        last_of_family = {}

        def trait(key, *fields):
            keys.append(key)
            lines.append(f"\t{key}:")
            lines.extend(f"\t\t{f}" for f in fields)

        for i, st in enumerate(data["stations"]):
            name = f"{tag.lower()}-s{i}"
            family = weapon_for(st["weapon"], station_missile(unit, st["weapon"], table["stations"][i]), used)
            stores = st["stores"]
            if st.get("internal"):
                names.append(name)
                trait(f"AmmoPool@{tag}S{i}", f"Name: {name}", f"Armaments: {name}", f"Ammo: {st['shots']}",
                      f"AmmoCondition: {name}")
                trait(f"Armament@{tag}S{i}", f"Name: {name}", f"Weapon: {family}", "LocalOffset: 0,0,-120",
                      f"PauseOnCondition: !{name}")
                continue
            if not stores:
                continue
            pair = len(stores) == 2
            names.append(name)
            pause = f"!{name}"
            if st["weapon"] in last_of_family:  # inner stations wait for the outer ones of the same weapon
                pause += f" || {last_of_family[st['weapon']]}"
            last_of_family[st["weapon"]] = name
            # Air-to-air missiles one per shot (Burst 1 alternates the listed pylons); ground ordnance in pairs
            # "ripple" (helicopter rocket pods, loadout_table.py): a fast stream from both pods, alternating pylons
            ripple = table["stations"][i].get("ripple")
            weapon = family + (".Ripple" if ripple else ".Pair" if pair and not st["weapon"].startswith("JetAAM") else "")
            muzzles = ", ".join(offset(s_["nose"], wdist, height) for s_ in stores)
            trait(f"AmmoPool@{tag}S{i}", f"Name: {name}", f"Armaments: {name}", f"Ammo: {st['shots'] * len(stores)}",
                  f"AmmoCondition: {name}")
            trait(f"Armament@{tag}S{i}", f"Name: {name}", f"Weapon: {weapon}", f"LocalOffset: {muzzles}",
                  f"PauseOnCondition: {pause}")
            for k, s_ in enumerate(stores):
                # Burst 2 fires the first listed pylon first: its sprite goes once the pool drops below 2
                need = 2 if pair and k == 0 else 1
                store = f"store-{i}{s_['side']}"
                trait(f"WithIdleOverlay@{tag}{store.upper().replace('-', '')}", f"Sequence: {store}",
                      f"RequiresCondition: {name} >= {need}")
                seq += [f"\t{store}:", f"\t\tFilename: ra|bits/hd/units/{sprite}-stores.png", f"\t\tStart: {frame}",
                        "\t\tLength: 1", "\t\tFacings: 32", "\t\tUseClassicFacings: False", "\t\tScale: 0.3333"]
                frame += 32
        if table.get("gun"):
            nose = max((s_["nose"] for st in data["stations"] for s_ in st["stores"]), key=lambda p: p[1],
                       default=[0, 2.0, 0.5])
            gun = f"{tag.lower()}-gun"
            trait(f"AmmoPool@{tag}GUN", f"Name: {gun}", f"Armaments: {gun}", f"Ammo: {GUN_AMMO}", f"AmmoCondition: {gun}")
            trait(f"Armament@{tag}GUN", f"Name: {gun}", f"Weapon: JetGun.{table['gun']}",
                  f"LocalOffset: {offset((0, nose[1] + 0.8, nose[2]), wdist, height)}", f"PauseOnCondition: !{gun}")
            names.append(gun)
        lines += ["\tAttackAircraft:", f"\t\tArmaments: {', '.join(names)}"]
        if cfg["kind"] == "heli":
            # Helicopters reload in the field (no trip back to the helipad): every pool refills by itself
            for n in names:
                trait(f"ReloadAmmoPool@{n.upper().replace('-', '')}", f"AmmoPool: {n}", "Delay: 60")
        else:
            # Rearmable only refills the pools it lists (default: primary): every station and the gun, at the airfield
            lines += ["\tRearmable:", f"\t\tAmmoPools: {', '.join(names)}"]
        fighter = any(st["weapon"].startswith("JetAAM") for st in data["stations"]) and not table.get("strike")
        built[actor] = (keys, fighter)
        blocks[actor] = lines
        seqs += seq
        print(f"{actor}: {len(names)} weapons ({frame // 32} weapon overlays){' - fighter' if fighter else ''}")

    def ancestors(a):
        while a in parent:
            a = parent[a]
            yield a

    actors = sorted(set(blocks) | {a for a in parent if any(p in built for p in ancestors(a))})
    for actor in actors:
        lines = [f"\n{actor}:"]
        inherited = [p for p in ancestors(actor) if p in built]
        if not inherited:
            # Remove the classic weapon the actor (or its MIG/YAK base) had; actors whose own block has no unnamed
            # Armament (the Longbow's were named, now removed by hand) only lose their ammo pool
            own = re.search(rf"^{re.escape(actor)}:\n((?:\t.*\n)+)", aircraft_rules, re.M)
            has_gun = own is None or "\tArmament:\n" in own.group(1) or re.search(r"\tInherits: (MIG|YAK|TRAN)\n", own.group(1))
            lines += (["\t-Armament:"] if has_gun else []) + ["\t-AmmoPool:"]
            if actor in blocks and MODELS.get(actor.lower(), {}).get("kind") == "heli":
                lines += ["\t-ReloadAmmoPool:"]  # it refilled the removed "primary" pool
        for p in inherited:  # a loadout jet's weapons and overlays are its own, not its children's
            lines += [f"\t-{k}:" for k in built[p][0]]
        if actor in blocks:
            lines += blocks[actor]
            fighter = built[actor][1]
        else:
            # Not in the loadout table: keeps the classic Maverick launcher its parent had before IDEA-34
            fighter = False
            lines += ORIGINAL_WEAPONS + ["\tRearmable:", "\t\tAmmoPools: primary"]
        parent_fighter = any(built[p][1] for p in inherited[:1])
        if fighter:
            lines += AIR_TARGETING
        elif parent_fighter:
            lines += GROUND_TARGETING
        rules += lines
    open(RULES, "w").write("\n".join(rules) + "\n")
    open(SEQUENCES, "w").write("\n".join(seqs) + "\n")
    # Missile variants: the family's weapon with another missile sprite (Pair variants for ground ordnance pairs)
    out = [HEADER.rstrip("\n"), "# Missile variants fired by the jets' stations (make_loadouts.py SIDE_MISSILES).", ""]
    for family, kind in sorted(used):
        for suffix in ("", ".Pair") + ((".Ripple",) if family == "JetRockets" else ()):
            out += [f"{family}.{kind}{suffix}:", f"\tInherits: {family}{suffix}", "\tProjectile: PxRocket",
                    f"\t\tSequence: {kind}", ""]
    open(MISSILE_WEAPONS, "w").write("\n".join(out))
    print(f"{len(used)} missile variants: {', '.join(f'{f}.{k}' for f, k in sorted(used))}")
    print("wrote", RULES, "and", SEQUENCES)


if __name__ == "__main__":
    main()
