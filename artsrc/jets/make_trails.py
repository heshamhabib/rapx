#!/usr/bin/env python3
"""
Writes mods/rapx/rules/jet-trails.yaml: real-looking trails (WithPxJetTrail, OpenRA.Mods.RAPX) for every plane with
an HD sprite (the flat Contrail lines were removed from rules/aircraft.yaml and husks.yaml). Engine and wingtip positions are measured on the plane's own sprite
(frame 0 faces north): the exhaust leaves the tail on the centreline, vapour leaves the outermost wing points.

  python3 artsrc/jets/make_trails.py

Sprite pixels -> world: the sprites are drawn at Scale 1/3, 24 screen px per 1024 world units; the 50 degree render
camera shortens nose-to-tail lengths, divided out with the same 0.88 compromise as the importer's offsets.
"""

import os
import re

import numpy as np
from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
MOD = os.path.join(ROOT, "mods", "rapx")
OUT = os.path.join(MOD, "rules", "jet-trails.yaml")
WORLD_PER_SPRITE_PX = 1024 / 24 / 3

# Aircraft with no jet engine: propeller planes get vapour only, airships nothing
PROPS = {"yak", "jet.mig3", "jet.la11"}
SKIP = {"jet.zeppelin", "jet.swarm", "tran", "heli", "hind", "mh60", "jet.v22"}
# Aircraft built on a helicopter in the rules but needing their own wreck: (wreck to inherit, effect size)
OWN_WRECK = {"jet.an225": ("MIG.Husk", 2.4), "jet.v22": ("TRAN.Husk", 1.2)}
JETLESS_EXHAUST = {"jet.an225"}


def idle_sprites():
    """image -> HD idle sprite file, from the sequence files (later files win, as in the game)."""
    out = {}
    for name in ("aircraft.yaml", "jets.yaml", "hd-units.yaml"):
        text = open(os.path.join(MOD, "sequences", name)).read()
        for m in re.finditer(r"\n([a-z0-9.\-]+):\n((?:\t[^\n]*\n)+)", text):
            idle = re.search(r"\tidle:\n(?:\t\t[^\n]*\n)*?\t\tFilename: ra\|bits/hd/units/([\w.\-]+\.png)", m.group(2))
            if idle:
                out[m.group(1)] = idle.group(1)
    return out


def actors():
    names = set()
    for name in ("aircraft.yaml", "jets.yaml"):
        names |= set(re.findall(r"^([A-Z0-9.]+):$", open(os.path.join(MOD, "rules", name)).read(), re.M))
    return names


def measure(path):
    im = Image.open(path)
    fw, fh = (int(v) for v in im.info["FrameSize"].split(","))
    a = np.asarray(im.convert("RGBA"))[:fh, :fw, 3] > 60
    ys, xs = np.nonzero(a)
    cx, cy = fw / 2, fh / 2
    band = np.abs(xs - cx) < fw * 0.03
    tail = ys[band].max() if band.any() else ys.max()
    tail -= (ys.max() - ys.min()) * 0.02  # just inside the nozzle
    left = xs.min()
    tip_y = ys[xs <= left + 1].mean()
    fwd = lambda py: round(-(py - cy) / 0.88 * WORLD_PER_SPRITE_PX)
    right = lambda px: round((px - cx) * WORLD_PER_SPRITE_PX)
    engine = (fwd(tail), 0)
    tip = (fwd(tip_y), right(cx + (cx - left)))
    return engine, tip


# Agile fighters that fly aerobatics; bombers, transports, attack jets, interceptors and the old jets fly level
AEROBATIC = {"jet.f16", "jet.f14", "jet.su27", "jet.su35", "mig", "jet.mig21", "jet.f22", "jet.typhoon", "jet.rafale",
             "jet.m2000", "jet.saeqeh", "jet.j20", "jet.yf23", "jet.su47"}
HUSKS = {"MIG": "MIG.Husk", "YAK": "YAK.Husk", "BADR": "BADR.Husk", "U2": "U2.Husk"}
PARENTS = {}


def ancestors(actor):
    while actor in PARENTS:
        actor = PARENTS[actor]
        yield actor


def wreck(actor, image, base, size):
    """The aircraft's own falling wreck: its own picture and name, crash effects sized to it."""
    out = [f"{actor}:", "\tSpawnActorOnDeath:", f"\t\tActor: {actor}.Husk", "",
           f"{actor}.Husk:", f"\tInherits: {base}", "\tRenderSprites:", f"\t\tImage: {image}",
           "\tWithPxCrashFx:", f"\t\tSize: {size:.2f}"]
    if actor in NAMES:
        out += ["\tTooltip:", f"\t\tName: {NAMES[actor]}"]
    return out + [""]


NAMES = {}


def main():
    for name in ("aircraft.yaml", "jets.yaml"):
        text = open(os.path.join(MOD, "rules", name)).read()
        for m in re.finditer(r"^([A-Z0-9.]+):\n\tInherits: ([A-Z0-9.^]+)$", text, re.M):
            PARENTS[m.group(1)] = m.group(2)
        for m in re.finditer(r"^([A-Z0-9.]+):\n((?:\t[^\n]*\n)+)", text, re.M):
            name = re.search(r"\tTooltip:\n(?:\t\t[^\n]*\n)*?\t\tName: (\S+)", m.group(2))
            if name:
                NAMES[m.group(1)] = name.group(1)
    sprites, known = idle_sprites(), actors()
    lines = ["# GENERATED by artsrc/jets/make_trails.py - edit that script, not this file.",
             "# Real-looking exhaust, afterburner glow and wingtip vapour (WithPxJetTrail) instead of Contrail lines.", ""]
    count = 0
    for image, sprite in sorted(sprites.items()):
        actor = image.upper()
        if actor not in known:
            continue
        if image in SKIP:
            if image in OWN_WRECK:
                lines += wreck(actor, image, *OWN_WRECK[image])
            continue
        path = os.path.join(MOD, "bits", "hd", "units", sprite)
        if not os.path.exists(path):
            continue
        (ef, er), (tf, tr) = measure(path)
        prop = image in PROPS
        lines += [f"{actor}:", "\tWithPxJetTrail:",
                  "\t\tRequiresCondition: airborne",
                  f"\t\tWingtips: {tf},{tr},0, {tf},{-tr},0"]
        if prop:
            lines += ["\t\tEngines: 0,0,0", "\t\tDensity: 0", "\t\tAfterburner: false", "\t\tVapourMin: 0.08"]
        else:
            lines += [f"\t\tEngines: {ef},{er},0"]
        if image in AEROBATIC:
            # Banks into turns, rolls when hit or in a dogfight, fires flares (OpenRA.Mods.RAPX WithPxAerobatics)
            lines += ["\tWithPxAerobatics:", "\t\tRequiresCondition: airborne"]
        lines.append("")
        # Its own wreck: falls with its own picture, crash effects sized to the plane (fighter = 1)
        husk = next((HUSKS[p] for p in ancestors(actor) if p in HUSKS), HUSKS.get(actor))
        if image in OWN_WRECK:
            lines += wreck(actor, image, *OWN_WRECK[image])
        elif husk:
            size = max(0.8, min(2.4, abs(tr) / 950))
            lines += wreck(actor, image, husk, size) if actor not in HUSKS else [
                f"{husk}:", "\tWithPxCrashFx:", f"\t\tSize: {size:.2f}", ""]
        count += 1
    open(OUT, "w").write("\n".join(lines))
    print(f"{count} aircraft -> {OUT}")


if __name__ == "__main__":
    main()
